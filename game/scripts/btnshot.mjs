import { chromium } from '@playwright/test';
import { readFileSync } from 'node:fs';
const [w, h, out] = process.argv.slice(2);
const b = await chromium.launch({ args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
const p = await (await b.newContext({ viewport: { width: +w, height: +h }, serviceWorkers: 'block' })).newPage();
await p.goto('http://localhost:4173/?test=1');
await p.click('[data-testid="start-button"]');
await p.waitForTimeout(1200);
await p.screenshot({ path: `test-results/screens/btn-${out}-disabled.png` });
await p.evaluate((j) => window.__HANG__.loadState(j), readFileSync('tests/e2e/fixtures/wallbreak.json', 'utf8'));
await p.waitForTimeout(800);
const c = await p.evaluate(() => window.__HANG__.cellToScreen(4, 4)); await p.mouse.click(c.x, c.y);
const d = await p.evaluate(() => window.__HANG__.cellToScreen(4, 5)); await p.mouse.click(d.x, d.y);
await p.waitForTimeout(600);
await p.screenshot({ path: `test-results/screens/btn-${out}-enabled.png` });
const e = await p.evaluate(() => window.__HANG__.cellToScreen(4, 3)); await p.mouse.click(e.x, e.y);
await p.waitForTimeout(600);
await p.screenshot({ path: `test-results/screens/btn-${out}-break.png` });
await b.close();
